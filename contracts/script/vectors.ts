// Writes contracts/test/Vectors.sol from the real TypeScript code, so the
// Solidity tests prove the contract builds byte-identical texts.
// Run from the repo root: node contracts/script/vectors.ts
import { writeFileSync } from "node:fs";
import { keccak_256 } from "@noble/hashes/sha3.js";
import { recipientCardFields, recipientCardText } from "@qorechain/qoreseal";
import { parseAddress } from "@qorechain/qoresign";
import { identityFromMnemonic } from "../../src/core/identity.ts";
import { changeText, deviceText, openText, writeText, sortByAddress, SITE } from "../../src/core/vault.ts";

const MNEMONIC = "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon art";
const CHAIN = "qorechain-diana";
const id = identityFromMnemonic(MNEMONIC);
const evm = "0x" + Buffer.from(parseAddress(id.address).bytes).toString("hex");
const fields = recipientCardFields({ chainId: CHAIN, address: id.address, keys: id.sealKeys, issuedAt: "2026-11-22T09:00:00Z" });
const card = recipientCardText(fields);
const file = "00112233445566778899aabbccddeeff";
const access = "a".repeat(64), data = "b".repeat(64);
const OTHER = "qor1wyvfhue6jja02pd2gqfm6rc6hl6jwv0afq5qja";
const readers = sortByAddress([id.address, OTHER]);
const change = changeText({ id: file, epoch: 3n, version: 12n, access, data, name: ".env", readers });
const REPLY = "ef".repeat(32);
const openT = openText({ file, epoch: 3n, version: 3n, reader: OTHER, replyKey: REPLY, nonce: 42n });
const writeT = writeText({ id: file, epoch: 3n, version: 13n, access, data, name: ".env", writer: OTHER });
const DEVICE_ID = "cd".repeat(32);
const deviceT = deviceText({ account: OTHER, id: DEVICE_ID, untilBlock: 123456n });
const evmOf = (a: string) => toChecksum("0x" + Buffer.from(parseAddress(a).bytes).toString("hex"));

const lit = (s: string) => `hex"${Buffer.from(s, "utf8").toString("hex")}"`;
const out = `// SPDX-License-Identifier: Apache-2.0
// Generated by contracts/script/vectors.ts from the TypeScript code. Do not edit.
pragma solidity ^0.8.28;

library Vectors {
    string internal constant CHAIN_ID = "${CHAIN}";
    address internal constant ACCOUNT = ${toChecksum(evm)};
    bytes internal constant ACCOUNT_BECH32 = ${lit(id.address)};
    bytes32 internal constant MLKEM_SHA3 = 0x${fields.mlkemKeySha3};
    bytes32 internal constant X25519 = 0x${fields.x25519PublicKey};
    string internal constant ISSUED_AT = "${fields.issuedAt}";
    bytes internal constant CARD_TEXT = ${lit(card)};
    bytes16 internal constant FILE = 0x${file};
    bytes32 internal constant ACCESS = 0x${access};
    bytes32 internal constant DATA = 0x${data};
    string internal constant SITE = "${SITE}";
    string internal constant NAME = ".env";
    address internal constant OTHER = ${evmOf(OTHER)};
    address internal constant READER_0 = ${evmOf(readers[0]!)}; // ascending address order
    address internal constant READER_1 = ${evmOf(readers[1]!)};
    bytes32 internal constant REPLY_KEY = 0x${REPLY};
    bytes internal constant OPEN_TEXT = ${lit(openT)}; // file FILE, epoch 3, version 3, reader OTHER, reply key REPLY_KEY, nonce 42
    bytes internal constant WRITE_TEXT = ${lit(writeT)}; // file FILE, epoch 3, version 13, ACCESS, DATA, NAME, writer OTHER
    bytes32 internal constant DEVICE_ID = 0x${DEVICE_ID};
    bytes internal constant DEVICE_TEXT = ${lit(deviceT)}; // account OTHER, until block 123456
    bytes internal constant CHANGE_TEXT = ${lit(change)};
}
`;
writeFileSync(new URL("../test/Vectors.sol", import.meta.url), out);
console.log("wrote contracts/test/Vectors.sol for", id.address);

function toChecksum(a: string) {
  const lower = a.slice(2).toLowerCase();
  const h = Buffer.from(keccak_256(new TextEncoder().encode(lower))).toString("hex");
  return "0x" + [...lower].map((c, i) => (parseInt(h[i] ?? "0", 16) >= 8 ? c.toUpperCase() : c)).join("");
}
